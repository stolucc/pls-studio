// Non-normal multivariate data by the Vale & Maurelli (1983) method.
//
// Each variable is a Fleishman (1978) polynomial of a standard normal,
// Y = a + bZ + cZ² + dZ³ (a = −c), with b, c, d chosen so that Y has mean 0,
// variance 1, the target skewness and excess kurtosis. The normals are drawn
// with an *intermediate* correlation ρ* per pair, chosen so that the Y's have
// exactly the target correlation:
//   r = ρ*(b₁b₂ + 3b₁d₂ + 3d₁b₂ + 9d₁d₂) + ρ*²(2c₁c₂) + ρ*³(6d₁d₂).
// Validated against high-precision R solutions (and Fleishman's own table).

import { cholesky, solve, type Mat } from './linalg';

export interface Fleishman {
  a: number;
  b: number;
  c: number;
  d: number;
}

const NORMAL: Fleishman = { a: 0, b: 1, c: 0, d: 0 };

function equations([b, c, d]: number[], skew: number, kurt: number): number[] {
  return [
    b * b + 6 * b * d + 2 * c * c + 15 * d * d - 1,
    2 * c * (b * b + 24 * b * d + 105 * d * d + 2) - skew,
    24 *
      (b * d +
        c * c * (1 + b * b + 28 * b * d) +
        d * d * (12 + 48 * b * d + 141 * c * c + 225 * d * d)) -
      kurt,
  ];
}

function jacobian([b, c, d]: number[]): Mat {
  return [
    [2 * b + 6 * d, 4 * c, 6 * b + 30 * d],
    [
      2 * c * (2 * b + 24 * d),
      2 * (b * b + 24 * b * d + 105 * d * d + 2),
      2 * c * (24 * b + 210 * d),
    ],
    [
      24 * (d + c * c * (2 * b + 28 * d) + d * d * 48 * d),
      24 * (2 * c * (1 + b * b + 28 * b * d) + d * d * 282 * c),
      24 *
        (b +
          c * c * 28 * b +
          2 * d * (12 + 48 * b * d + 141 * c * c + 225 * d * d) +
          d * d * (48 * b + 450 * d)),
    ],
  ];
}

/** Fleishman coefficients for a target skewness and excess kurtosis (damped Newton from (1, 0, 0)). */
export function fleishman(skew: number, kurt: number): Fleishman {
  if (skew === 0 && kurt === 0) return { ...NORMAL };
  const norm2 = (v: number[]) => v.reduce((s, x) => s + x * x, 0);
  // A few starting points: the classic (1, 0, 0) and ones nearer high-kurtosis solutions.
  for (const start of [
    [1, 0, 0],
    [0.9, skew / 10, 0.05],
    [0.7, skew / 6, 0.1],
  ]) {
    let x = start.slice();
    let f = equations(x, skew, kurt);
    for (let it = 0; it < 200 && norm2(f) > 1e-28; it++) {
      let step: number[];
      try {
        step = solve(jacobian(x), f);
      } catch {
        break;
      }
      let t = 1,
        accepted = false;
      for (let h = 0; h < 40; h++, t /= 2) {
        const cand = x.map((v, k) => v - t * step[k]);
        const fc = equations(cand, skew, kurt);
        if (norm2(fc) < norm2(f)) {
          x = cand;
          f = fc;
          accepted = true;
          break;
        }
      }
      if (!accepted) break;
    }
    if (norm2(f) < 1e-24 && x[0] > 0) return { a: -x[1], b: x[0], c: x[1], d: x[2] };
  }
  throw new Error(
    `Skewness ${skew} with excess kurtosis ${kurt} cannot be generated by the Fleishman method (kurtosis must be at least about 1.5·skew² − 1.2).`,
  );
}

/** Intermediate normal correlation giving correlation r between two Fleishman variables. */
export function intermediateCor(f1: Fleishman, f2: Fleishman, r: number): number {
  const k1 = f1.b * f2.b + 3 * f1.b * f2.d + 3 * f1.d * f2.b + 9 * f1.d * f2.d;
  const k2 = 2 * f1.c * f2.c,
    k3 = 6 * f1.d * f2.d;
  const g = (p: number) => p * k1 + p * p * k2 + p * p * p * k3 - r;
  // Real roots in [−1, 1]: bracket on a fine grid, refine by bisection; take the one closest to r.
  const roots: number[] = [];
  const N = 400;
  let prev = g(-1);
  for (let i = 1; i <= N; i++) {
    const x = -1 + (2 * i) / N,
      cur = g(x);
    if (prev === 0) roots.push(-1 + (2 * (i - 1)) / N);
    else if (Math.sign(prev) !== Math.sign(cur)) {
      let lo = -1 + (2 * (i - 1)) / N,
        hi = x,
        glo = prev;
      for (let k = 0; k < 100; k++) {
        const mid = (lo + hi) / 2,
          gm = g(mid);
        if (Math.sign(gm) === Math.sign(glo)) {
          lo = mid;
          glo = gm;
        } else hi = mid;
      }
      roots.push((lo + hi) / 2);
    }
    prev = cur;
  }
  if (g(1) === 0) roots.push(1);
  if (roots.length === 0)
    throw new Error(
      `Correlation ${r.toFixed(3)} cannot be reached with these skewness/kurtosis values (Vale–Maurelli).`,
    );
  return roots.reduce((best, x) => (Math.abs(x - r) < Math.abs(best - r) ? x : best));
}

export interface ValeMaurelli {
  coef: Fleishman[];
  /** Cholesky factor of the intermediate correlation matrix. */
  L: Mat;
}

/** Prepare Vale–Maurelli generation for a correlation matrix and per-variable skewness/kurtosis. */
export function valeMaurelli(R: Mat, skew: number[], kurt: number[]): ValeMaurelli {
  const coef = R.map((_, i) => fleishman(skew[i], kurt[i]));
  const Rs = R.map((row, i) =>
    row.map((r, j) => (i === j ? 1 : i < j ? intermediateCor(coef[i], coef[j], r) : NaN)),
  );
  for (let i = 0; i < R.length; i++) for (let j = 0; j < i; j++) Rs[i][j] = Rs[j][i];
  const L = cholesky(Rs);
  if (!L)
    throw new Error(
      'The intermediate correlation matrix is not positive definite: this combination of correlations, skewness and kurtosis cannot be generated (Vale–Maurelli).',
    );
  return { coef, L };
}

/** Mplus MODEL = NOCOVARIANCES: every pair of the twin factors uncorrelated but the A and the C pairs. */
const uncorrelated = (fs: string[]) =>
  fs.flatMap((a, i) =>
    fs
      .slice(i + 1)
      .filter((b) => !(a[0] === b[0] && 'ac'.includes(a[0])))
      .map((b) => `${a} ~~ 0*${b}`),
  );


// AMOS Graphics files (.amw): a small model written in AMOS's own layout (UTF-16,
// sections, attribute list, one value per attribute per object) is read back as
// lavaan syntax and as AMOS's diagram.

import { describe, expect, it } from 'vitest';
import { amosDiagram, amosValue, decodeAmw, parseAmw } from './amos';
import { parseLavaanSyntax } from './syntax';

const ATTRS = ['o_type,4', 'originx,5', 'originy,5', 'obj1,4', 'obj2,4', 'value1,2', 'value2,2', 'label,1'];
const NUM = '\x01', FREE = '\x02';
/** One object: type, x, y, obj1, obj2, value1, value2, label (in ATTRS order). */
type Obj = [number, number, number, number, number, string, string, string];
const v = (x: number, y: number, label: string, type = 1): Obj => [type, x, y, 0, 0, FREE, FREE, label];
const arrow = (from: number, to: number, value = FREE, type = 4): Obj => [type, 0, 0, from, to, value, FREE, ''];

function amw(objects: Obj[], dollar: string[] = ['$ml', '$dobootstrap=1', '$bootstrap=500', '$confidencepc=90', '$seed=7', '$nomeansintercepts', '$unbiased', '$usebiased'], groups = 1) {
  const lines = ['!@!!Please do not edit this file', '!@!pr', 'means=False', 'endpr', '!@!ee', '!@!dollar', ...dollar, '$model', 'Default model', '', 'EndDollar', '!@!ee',
    '!@!ng', String(groups), '!@!at', String(ATTRS.length), ...ATTRS, '!@!ee', '!@!ob', String(objects.length), ...objects.flatMap((o) => o.map(String)), '!@!ee',
    '!@!dbname', 'study.sav.sav', '!@!dbtype', '2', '!@!xx'];
  const text = '﻿' + lines.join('\r\n');
  const bytes = new Uint8Array(text.length * 2);
  for (let i = 0; i < text.length; i++) { bytes[2 * i] = text.charCodeAt(i) & 0xff; bytes[2 * i + 1] = text.charCodeAt(i) >> 8; }
  return bytes;
}

// 1 F (factor) measured by 2 x1 (marker), 3 x2, 4 x3; 5–7 their error terms; 8 the observed control age;
// 9 Y (factor) by 10 y1, 11 y2, errors 12, 13; disturbance 14 of Y; 15 group (observed control).
const objects: Obj[] = [
  v(2, 3, 'F', 2), v(1, 5, 'x1'), v(2, 5, 'x2'), v(3, 5, 'x3'), v(1, 6, 'e1', 2), v(2, 6, 'e2', 2), v(3, 6, 'e3', 2), v(1, 1, 'age'),
  v(6, 3, 'Y', 2), v(5.5, 5, 'y1'), v(6.5, 5, 'y2'), v(5.5, 6, 'e4', 2), v(6.5, 6, 'e5', 2), v(7, 2, 'd1', 2), v(1, 2, 'group'),
  arrow(1, 2, `${NUM}1`), arrow(1, 3), arrow(1, 4), arrow(5, 2, `${NUM}1`), arrow(6, 3, `${NUM}1`), arrow(7, 4, `${NUM}1`),
  arrow(9, 10, `${NUM}1`), arrow(9, 11), arrow(12, 10, `${NUM}1`), arrow(13, 11, `${NUM}1`), arrow(14, 9, `${NUM}1`),
  arrow(1, 9, 'b1'), arrow(8, 9), arrow(15, 9),
  arrow(8, 1, FREE, 8), arrow(6, 7, FREE, 8),
];

describe('AMOS Graphics files', () => {
  it('reads the values: \\x01 a fixed number, \\x02 free, other text a label', () => {
    expect(amosValue(`${NUM}1`)).toEqual({ fixed: 1 });
    expect(amosValue(`${NUM}0.5`)).toEqual({ fixed: 0.5 });
    expect(amosValue(FREE)).toEqual({});
    expect(amosValue('b1')).toEqual({ label: 'b1' });
  });

  it('decodes UTF-16 and writes the model as lavaan syntax: factors with their marker first, paths, covariances (of error terms: residual)', () => {
    const m = parseAmw(decodeAmw(amw(objects)));
    expect(m.syntax.split('\n')).toEqual([
      'F =~ 1*x1 + x2 + x3',
      'Y =~ 1*y1 + y2',
      'Y ~ b1*F + age + group',
      'age ~~ F',
      'x2 ~~ x3',
    ]);
    expect(m.covariances).toEqual([['age', 'F']]);
    expect(m.dataFile).toBe('study.sav');
    expect(m.groups).toBe(1);
    expect(m.positions.F).toEqual({ x: 2, y: 3 });
    expect(m.positions.e1).toBeUndefined();
  });

  it('carries the analysis properties over: estimator, bootstrap, confidence, seed, means, the covariance convention', () => {
    const m = parseAmw(decodeAmw(amw(objects)));
    expect(m.settings).toEqual({ estimator: 'ML', bootSamples: 500, confidence: 0.9, seed: 7, means: false, unbiasedAnalysis: false });
    expect(parseAmw(decodeAmw(amw(objects, ['$gls', '$useunbiased']))).settings).toMatchObject({ estimator: 'GLS', unbiasedAnalysis: true, means: true });
    expect(parseAmw(decodeAmw(amw(objects, ['$ml'], 2))).warnings.some((w) => /2 groups/.test(w))).toBe(true);
  });

  it('builds AMOS’s diagram: observed controls with free variances, covariances only where drawn (the rest zero), AMOS’s positions', () => {
    const amos = parseAmw(decodeAmw(amw(objects)));
    const parsed = parseLavaanSyntax(amos.syntax);
    const d = amosDiagram(parsed.model, amos);
    const c = (n: string) => d.constructs.find((k) => k.name === n)!;
    expect(d.constructs.map((k) => k.name).sort()).toEqual(['F', 'Y', 'age', 'group']);
    expect(c('age').covariate).toBeUndefined();
    expect(c('group').indicators).toEqual(['group']);
    expect(c('F').indicators).toEqual(['x1', 'x2', 'x3']);
    expect(c('F').x).toBe(220); expect(c('F').y).toBe(330);
    const pair = (a: string, b: string) => d.correlations!.find((k) => k.kind === 'construct' && [k.a, k.b].sort().join() === [c(a).id, c(b).id].sort().join());
    expect(pair('age', 'F')?.zero).toBeUndefined();  // drawn: free
    expect(pair('age', 'group')?.zero).toBe(true);   // not drawn: AMOS fixes it at zero
    expect(pair('F', 'group')?.zero).toBe(true);
    expect(d.correlations!.some((k) => k.kind === 'indicator' && [k.a, k.b].sort().join() === 'x2,x3')).toBe(true);
    expect(d.paths.find((p) => p.from === c('F').id && p.to === c('Y').id)?.label).toBe('b1');
  });

  it('refuses other files', () => {
    expect(() => parseAmw('a,b\n1,2')).toThrow(/Not an AMOS Graphics model file/);
    expect(() => decodeAmw(new Uint8Array(6_000_000))).toThrow(/too large/);
  });
});

